export const hexToRgb = (hex: string): [number, number, number] => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)) as [number, number, number];
};

const channel = (v: number) => {
  const c = v / 255;
  return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
};

export const luminance = (hex: string) => {
  const [r, g, b] = hexToRgb(hex);
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
};

export const contrast = (a: string, b: string) => {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};

export const isDark = (hex: string) => luminance(hex) < 0.3;

export const formatColor = (hex: string, format: "HEX" | "RGB") =>
  format === "HEX" ? hex.toUpperCase() : `RGB ${hexToRgb(hex).join(", ")}`;

export const formatRatio = (n: number) => `${n.toFixed(1).replace(".", ",")} : 1`;
